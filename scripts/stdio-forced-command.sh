#!/bin/sh
set -eu
umask 077

PRINCIPAL=${1-}
case "$PRINCIPAL" in
    owner|partner) ;;
    *) exit 64 ;;
esac

# Build a new environment instead of inheriting any SSH/client variables.
HOME=/var/lib/claude-mcp
PATH=/opt/claude-code/2.1.236:/usr/local/bin:/usr/bin:/bin
CLAUDE_BIN=/opt/claude-code/2.1.236/claude
CLAUDE_MCP_WORK_ROOT=/var/lib/claude-mcp/research
CLAUDE_MCP_PRINCIPAL=$PRINCIPAL
CLAUDE_MCP_PRINCIPALS=owner,partner
CLAUDE_MCP_MODELS='{"opus":{"cli_value":"opus","family":"opus","min_cli_version":"2.1.236"}}'
CLAUDE_MCP_REQUIRED_CLI_VERSION=2.1.236
CLAUDE_MCP_PROMPT_LIMIT=20000
CLAUDE_MCP_RATE_LIMIT_PER_HOUR=20
CLAUDE_MCP_CONCURRENCY=1
CLAUDE_MCP_OUTPUT_LIMIT=100000
CLAUDE_MCP_RESULT_LIMIT=100000
CLAUDE_MCP_STATUSLINE_OBSERVATION="$CLAUDE_MCP_WORK_ROOT/state/statusline-observation.json"
CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1
CLAUDE_CODE_DISABLE_OFFICIAL_MARKETPLACE_AUTOINSTALL=1
DISABLE_AUTOUPDATER=1
DISABLE_ERROR_REPORTING=1
DISABLE_FEEDBACK_COMMAND=1
DISABLE_TELEMETRY=1
DO_NOT_TRACK=1
CLAUDE_CODE_DISABLE_FEEDBACK_SURVEY=1
LANG=C.UTF-8
LC_ALL=C.UTF-8
NO_COLOR=1

cd /var/lib/claude-mcp
exec /usr/bin/env -i \
    HOME="$HOME" \
    PATH="$PATH" \
    CLAUDE_BIN="$CLAUDE_BIN" \
    CLAUDE_MCP_WORK_ROOT="$CLAUDE_MCP_WORK_ROOT" \
    CLAUDE_MCP_PRINCIPAL="$CLAUDE_MCP_PRINCIPAL" \
    CLAUDE_MCP_PRINCIPALS="$CLAUDE_MCP_PRINCIPALS" \
    CLAUDE_MCP_MODELS="$CLAUDE_MCP_MODELS" \
    CLAUDE_MCP_REQUIRED_CLI_VERSION="$CLAUDE_MCP_REQUIRED_CLI_VERSION" \
    CLAUDE_MCP_PROMPT_LIMIT="$CLAUDE_MCP_PROMPT_LIMIT" \
    CLAUDE_MCP_RATE_LIMIT_PER_HOUR="$CLAUDE_MCP_RATE_LIMIT_PER_HOUR" \
    CLAUDE_MCP_CONCURRENCY="$CLAUDE_MCP_CONCURRENCY" \
    CLAUDE_MCP_OUTPUT_LIMIT="$CLAUDE_MCP_OUTPUT_LIMIT" \
    CLAUDE_MCP_RESULT_LIMIT="$CLAUDE_MCP_RESULT_LIMIT" \
    CLAUDE_MCP_STATUSLINE_OBSERVATION="$CLAUDE_MCP_STATUSLINE_OBSERVATION" \
    CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC="$CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC" \
    CLAUDE_CODE_DISABLE_OFFICIAL_MARKETPLACE_AUTOINSTALL="$CLAUDE_CODE_DISABLE_OFFICIAL_MARKETPLACE_AUTOINSTALL" \
    DISABLE_AUTOUPDATER="$DISABLE_AUTOUPDATER" \
    DISABLE_ERROR_REPORTING="$DISABLE_ERROR_REPORTING" \
    DISABLE_FEEDBACK_COMMAND="$DISABLE_FEEDBACK_COMMAND" \
    DISABLE_TELEMETRY="$DISABLE_TELEMETRY" \
    DO_NOT_TRACK="$DO_NOT_TRACK" \
    CLAUDE_CODE_DISABLE_FEEDBACK_SURVEY="$CLAUDE_CODE_DISABLE_FEEDBACK_SURVEY" \
    LANG="$LANG" \
    LC_ALL="$LC_ALL" \
    NO_COLOR="$NO_COLOR" \
    PYTHONNOUSERSITE=1 \
    PYTHONDONTWRITEBYTECODE=1 \
    /opt/claude-research-mcp/current/.venv/bin/claude-research-mcp
